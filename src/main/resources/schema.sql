CREATE TABLE IF NOT EXISTS inventory_node (
  id VARCHAR(36) PRIMARY KEY,
  parent_id VARCHAR(36) REFERENCES inventory_node(id),
  name VARCHAR(120) NOT NULL,
  code VARCHAR(60) NOT NULL UNIQUE,
  kind VARCHAR(20) NOT NULL CHECK (kind IN ('SPACE','FURNITURE','CONTAINER','ITEM')),
  status VARCHAR(20) NOT NULL CHECK (status IN ('AVAILABLE','IN_USE','MAINTENANCE')),
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 100000),
  unit_value DECIMAL(14,2) NOT NULL CHECK (unit_value >= 0),
  responsible VARCHAR(120) NOT NULL,
  description VARCHAR(2000) NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS app_metadata (meta_key VARCHAR(60) PRIMARY KEY, meta_value VARCHAR(120) NOT NULL);
CREATE INDEX IF NOT EXISTS idx_node_parent ON inventory_node(parent_id);
ALTER TABLE inventory_node ADD COLUMN IF NOT EXISTS visibility VARCHAR(20) DEFAULT 'PUBLIC' NOT NULL CHECK (visibility IN ('PUBLIC','CONFIDENTIAL'));
CREATE TABLE IF NOT EXISTS inventory_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  node_id VARCHAR(36) NOT NULL,
  node_name VARCHAR(120) NOT NULL,
  action VARCHAR(40) NOT NULL,
  origin VARCHAR(2000) NOT NULL,
  destination VARCHAR(2000) NOT NULL,
  occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
ALTER TABLE inventory_event ADD COLUMN IF NOT EXISTS actor VARCHAR(120) DEFAULT 'Sistema' NOT NULL;
CREATE TABLE IF NOT EXISTS directory_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor VARCHAR(120) NOT NULL,
  target VARCHAR(120) NOT NULL,
  operation VARCHAR(120) NOT NULL,
  occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
